def remove_legacy_manual_sections(document):
    """Remove superseded short manual plans while keeping recorded results."""
    body = document.element.body
    for start_title, end_title in [
        ('План ручной проверки', 'Основание отчёта'),
        ('Быстрая ручная демонстрация', None),
    ]:
        start = next(p._p for p in document.paragraphs if p.text == start_title)
        current = start
        while current is not None:
            following = current.getnext()
            if current is not start:
                matching = next((p for p in document.paragraphs if p._p is current), None)
                if matching and ((end_title and matching.text == end_title) or matching.style.name == 'Heading 1'):
                    break
                if not end_title and current.tag.endswith('}p') and current.findall('.//{http://schemas.openxmlformats.org/wordprocessingml/2006/main}hyperlink'):
                    break
            body.remove(current)
            current = following


