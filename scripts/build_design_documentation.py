"""Build the independent design rationale with verifiable examples."""
from docx.shared import Inches

import document_reservations
import document_refresh
from document_common import ROOT, add_contents, cover, new_document, page, paragraph, save_document, table
from document_screenshots import add_cropped_screenshot


def build():
    """Describe the actual visual decisions of configuration 1.2.0."""
    doc=new_document('Обоснование дизайна')
    cover(doc,'Обоснование выбора дизайна')
    page(doc,'1 Назначение оформления')
    paragraph(doc,'Документ обосновывает оформление конфигурации «Молочная ферма Луговая», версия 1.2.0. Пользователь оформляет поступления и продажи, работает с перечнем продукции и сверяет отчёты. Поэтому визуальные решения подчинены выбору команды, вводу данных и чтению результата.')
    doc.add_heading('Основные решения',level=2)
    paragraph(doc,'Зелёный используется как основной акцент с учётом сельскохозяйственной темы. Светлый фон оставляет поля и таблицы читаемыми. Команды объединены по назначению: документы, справочные данные и проверка результатов. Фотография помогает различать продукцию в карточке.')
    table(doc,['Задача пользователя','Решение'],[
        ('Найти нужную операцию','Отдельные страницы Покупка и Продажа; подписи кнопок содержат действие.'),
        ('Отличить основной шаг от вспомогательного','Основные кнопки зелёные, журналы и вспомогательные действия имеют светлый фон.'),
        ('Проверить введённые значения','Сумма строки и итог документа выводятся отдельно от полей ввода.'),
        ('Прочитать отчёт','Зелёная шапка с белым текстом, строки данных на светлом фоне, числовые значения с форматом.'),
        ('Определить товар','Наименование, единица измерения и фотография находятся в карточке продукции.'),
    ],[2.25,4.4])
    doc.add_heading('Область применения',level=2)
    paragraph(doc,'Настройки относятся к разработанным формам, кнопкам и табличным отчётам. Стандартные панели и часть элементов оформления определяет платформа 1С. Системная жёлтая панель на снимках не является ошибкой применения выбранной палитры.')
    paragraph(doc,'Оформление презентации использует ту же палитру, но её шрифты и композиция не определяют внешний вид клиента 1С. Макеты интерфейса не подменяют снимки работающей базы.')

    page(doc,'2 Цвета и типографика')
    table(doc,['Цвет','Код','Назначение'],[
        ('Зелёный','#2F6B4F','Фон основных кнопок, текст названия фермы, шапки отчётов.'),
        ('Светлый зелёный','#E6EFE7','Фон кнопок журналов и вспомогательных действий.'),
        ('Тёмный зелёный','#20382C','Текст на светлых кнопках; основной текст презентации.'),
        ('Кремовый','#F8F6EE','Заданный фон форм и фон презентации.'),
        ('Белый','#FFFFFF','Текст на основных кнопках и заголовках отчётных таблиц.'),
        ('Светлый фон строк','#EDF4ED','Чередующиеся строки табличного отчёта.'),
    ],[1.5,1.1,4.05])
    paragraph(doc,'Коды соответствуют настройкам модулей форм. Отображение заданного фона и кнопок может различаться в зависимости от клиента и системной темы. В отчётах цвет применяется к ячейкам табличного документа.')
    doc.add_heading('Иерархия текста',level=2)
    paragraph(doc,'Название фермы выделено более крупным полужирным шрифтом. Ниже размещено назначение системы. Названия групп отделяют операции от справочной информации и отчётов. В отчёте заголовок отличается от подписей колонок; количество и суммы остаются в строках данных.')
    paragraph(doc,'Подписи кнопок указывают результат действия: «Оформить приход продукции», «Журнал продаж», «Остатки на складе». Значение команды передаётся текстом, а не одним цветом. Системный шрифт форм выбирается платформой, отдельно задаются только необходимые акценты.')
    doc.add_heading('Ограничения оценки',level=2)
    paragraph(doc,'Количественная проверка контрастности и исследование удобства с группой пользователей не проводились. Читаемость следует проверять на компьютере защиты при фактическом масштабе окна. Формальное соответствие стандартам доступности не заявляется.')

    page(doc,'3 Размещение элементов и навигация')
    add_cropped_screenshot(doc,'Рабочий_стол.png',(1624,1252),(35,475,1259,995),'Общий рабочий стол с группами команд',width=6.6)
    paragraph(doc,'Рисунок 1 Группы команд общего рабочего стола')
    paragraph(doc,'Снимок показывает общий рабочий стол. Слева расположены создание и просмотр документов, в центре продукция и цены, справа отчёты. Основное действие и открытие журнала имеют разные подписи и фон. На снимке показан рабочий стол до добавления кнопок бронирования.')
    doc.add_heading('Страницы разделов',level=2)
    paragraph(doc,'Покупка и Продажа открывают собственные страницы одной командой. В Покупке представлены поступления и поставщики, в Продаже продажи и покупатели. Общие справочники и остатки доступны с этих страниц. Подписи кнопок и правила цвета согласованы с общим рабочим столом.')
    doc.add_heading('Права и видимость',level=2)
    paragraph(doc,'Набор команд зависит от роли. Пользователь Покупка не получает кнопку создания продажи, пользователь Продажа кнопку создания прихода. Это сокращает число неподходящих действий. Скрытие кнопки дополняется правами метаданных, а не заменяет их.')
    paragraph(doc,'Автоматические проверки подтверждают создание страниц и их команд. Поведение панели разделов при щелчке мышью требует ручной проверки; результат такой проверки отдельно не зафиксирован.')

    page(doc,'4 Изображения и оформление отчётов')
    paragraph(doc,'В карточках используются изображения молока, творога и сметаны. Они созданы ImageGen для учебного проекта и не являются фотографиями реальной фермы. Изображение хранится в базе вместе с карточкой товара, поэтому его не нужно искать в отдельной папке при обычной работе.')
    images=doc.add_table(rows=1,cols=3)
    images.autofit=False
    for cell,file,label in zip(images.rows[0].cells,['milk.png','curd.png','cream.png'],['Молоко 3,2%','Творог 9%','Сметана 20%']):
        cell.width=Inches(2.2)
        cell.paragraphs[0].add_run().add_picture(str(ROOT/'assets'/file),width=Inches(2.05))
        cell.add_paragraph(label)
    paragraph(doc,'Рисунок 2 Учебные изображения продукции')
    paragraph(doc,'Поле картинки сохраняет пропорции изображения. Пользователь загружает PNG или JPEG кнопкой «Загрузить фотографию» и записывает карточку. В стандартном списке продукции миниатюры не выводятся.')
    doc.add_heading('Табличные результаты',level=2)
    add_cropped_screenshot(doc,'Остатки.png',(1906,840),(875,530,1752,680),'Заголовки и данные отчета по остаткам',width=6.6)
    paragraph(doc,'Рисунок 3 Фрагмент результата отчёта')
    paragraph(doc,'Снимок ранней версии иллюстрирует цвет шапки и чтение данных. В версии 1.2.0 отчёт содержит единицы, отборы, складское количество, резерв и свободный остаток. Количество молока в литрах и количество творога и сметаны в килограммах проверяются отдельно.')

    page(doc,'5 Проверка оформления')
    paragraph(doc,'Приёмка оформления проводится в работающей базе. Ниже приведены критерии ручного осмотра. Они не являются протоколом уже выполненных действий.')
    table(doc,['Объект','Критерий'],[
        ('Рабочий стол','Названия групп и кнопок читаются, команды не перекрывают друг друга.'),
        ('Покупка и Продажа','Открывается нужная страница, видны только доступные по роли операции.'),
        ('Документ','Поля не обрезаны, суммы и итог различимы, выбранная строка определяется перед удалением.'),
        ('Карточка продукции','Изображение видно без искажения пропорций; наименование и единица доступны для чтения.'),
        ('Отчёт','Заголовки, единицы и числа читаются; даты и отборы соответствуют результату.'),
        ('Печать','В установленной учебной версии недоступна из-за ограничения лицензии.'),
    ],[1.8,4.85])
    doc.add_heading('Подтверждённые сведения',level=2)
    paragraph(doc,'Наличие фотографий в хранилище проверено тремя сценариями T05. Создание карточки с полем картинки проверено F01. Команды рабочего стола и страниц разделов проверены F06, F08, F09 и F10. Эти сценарии подтверждают работу объектов, но не заменяют визуальный осмотр.')
    doc.add_heading('Основание описания',level=2)
    paragraph(doc,'Использованы модули форм рабочего стола, страниц Покупка и Продажа, документов и отчётов версии 1.2.0. Снимки интерфейса предоставлены пользователем. Связанные материалы: общая документация, инструкция пользователя и документация по тестированию в соответствующих папках комплекта.')
    document_reservations.design(doc)
    document_refresh.design(doc)
    add_contents(doc,[p.text for p in doc.paragraphs if p.style.name=='Heading 1'])
    save_document(doc,'design','Обоснование выбора дизайна Молочная ферма Луговая')


if __name__=='__main__':
    build()
