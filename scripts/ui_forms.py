def enhance_document(name, source):
    """Add clear row actions and a monetary total to a document form."""
    label = 'Поступление продукции' if name == 'Приход' else 'Продажа продукции'
    source = source.replace('Процедура СтрокаПриИзменении(Элемент)', 'Процедура СтрокаПриИзменении(Элемент) Экспорт')
    source = source.replace('    ЦветФона =', f'    Заголовок = "{label}";\n    АвтоЗаголовок = Ложь;\n    ЦветФона =', 1)
    source = source.replace('    Таблица = Элементы.Добавить', '''    ДобавитьКнопку("ДобавитьПродукцию", "Добавить продукцию");
    ДобавитьКнопку("УдалитьСтроку", "Удалить выбранную строку");
    Таблица = Элементы.Добавить''', 1)
    source = source.replace('    Элементы.ТоварыСумма.ТолькоПросмотр', '''    ДобавитьПоле("ИтогоДокумента", "ИтогоДокумента", "Итого, руб.");
    Элементы.ИтогоДокумента.ТолькоПросмотр = Истина;
    Элементы.ИтогоДокумента.Формат = "ЧДЦ=2";
    ИтогоДокумента = Объект.Товары.Итог("Сумма");
    Элементы.ТоварыСумма.ТолькоПросмотр''', 1)
    source = source.replace('        СтрокаТовара.Сумма = Окр(СтрокаТовара.Количество * СтрокаТовара.Цена, 2);', '''        СтрокаТовара.Сумма = Окр(СтрокаТовара.Количество * СтрокаТовара.Цена, 2);
        ИтогоДокумента = Объект.Товары.Итог("Сумма");''', 1)
    source += '''
&НаКлиенте
Процедура ДобавитьПродукцию(Команда) Экспорт
    СтрокаТовара = Объект.Товары.Добавить();
    СтрокаТовара.Количество = 1;
КонецПроцедуры

&НаКлиенте
Процедура УдалитьСтроку(Команда) Экспорт
    СтрокаТовара = Элементы.Товары.ТекущиеДанные;
    Если СтрокаТовара <> Неопределено Тогда
        Объект.Товары.Удалить(СтрокаТовара);
        ИтогоДокумента = Объект.Товары.Итог("Сумма");
    КонецЕсли;
КонецПроцедуры
'''
    return source


