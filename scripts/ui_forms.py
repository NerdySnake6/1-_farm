def section_module(section):
    """Reuse the home layout for a single purchase or sales section."""
    source = HOME_MODULE.replace('Заголовок = "Рабочий стол фермы";',
                                 f'Заголовок = "{section} продукции";')
    if section == 'Покупка':
        source = source.replace('''    Если РольДоступна("Продажа") Или РольДоступна("ПолныеПрава") Тогда
        ДобавитьКнопку("СоздатьРасход", "Оформить продажу продукции", Операции);
        ДобавитьКнопку("ОткрытьРасходы", "Журнал продаж", Операции);
    КонецЕсли;
''', '').replace('''    Если РольДоступна("Продажа") Или РольДоступна("ПолныеПрава") Тогда
        ДобавитьКнопку("ОткрытьПродажи", "Отчёт о продажах", ГруппаОтчетов);
    КонецЕсли;
''', '')
        counterpart = ('ОткрытьПоставщиков', 'Поставщики', 'Поставщики')
    else:
        source = source.replace('''    Если РольДоступна("Покупка") Или РольДоступна("ПолныеПрава") Тогда
        ДобавитьКнопку("СоздатьПриход", "Оформить приход продукции", Операции);
        ДобавитьКнопку("ОткрытьПриходы", "Журнал поступлений", Операции);
    КонецЕсли;
''', '')
        counterpart = ('ОткрытьПокупателей', 'Покупатели', 'Покупатели')
    command, caption, catalog = counterpart
    extra_buttons = (
        f'    ДобавитьКнопку("{command}", "{caption}", ГруппаСправочников);\n'
        '    ДобавитьКнопку("ОткрытьОрганизации", "Организации", ГруппаСправочников);\n'
        '    ДобавитьКнопку("ОткрытьСклады", "Склады", ГруппаСправочников);\n'
    )
    source = source.replace('    ДобавитьКнопку("ОткрытьОстатки",',
                            extra_buttons + '    ДобавитьКнопку("ОткрытьОстатки",', 1)
    for name, target in [(command, catalog), ('ОткрытьОрганизации', 'Организации'),
                         ('ОткрытьСклады', 'Склады')]:
        source += (f'\n&НаКлиенте\nПроцедура {name}(Команда) Экспорт\n'
                   f'    ОткрытьФорму("Справочник.{target}.ФормаСписка");\n'
                   'КонецПроцедуры\n')
    return source
