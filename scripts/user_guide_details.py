"""Detailed practical workflows for the dairy farm user guide."""
from build_testing_documentation import page, paragraph, table


def steps(document, items, start=1):
    """Add a numbered workflow with explicit actions and checks."""
    for index, text in enumerate(items, start):
        paragraph(document, f'{index}. {text}')


