def section(document, title, anchor):
    """Start a section and create a target for the contents hyperlinks."""
    heading = document.add_heading(title, level=1)
    heading.paragraph_format.page_break_before = True
    marker = OxmlElement('w:bookmarkStart')
    marker.set(qn('w:id'), str(100 + len(document.paragraphs)))
    marker.set(qn('w:name'), anchor)
    end = OxmlElement('w:bookmarkEnd')
    end.set(qn('w:id'), marker.get(qn('w:id')))
    heading._p.insert(0, marker)
    heading._p.append(end)


def contents(document):
    """Add a compact contents page with clickable section names."""
    section(document, 'Содержание', 'contents')
    for title, anchor, number in CONTENTS:
        item = document.add_paragraph()
        item.paragraph_format.space_after = Pt(10)
        item.paragraph_format.tab_stops.add_tab_stop(Cm(16.65), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        link = OxmlElement('w:hyperlink')
        link.set(qn('w:anchor'), anchor)
        link.set(qn('w:history'), '1')
        run = OxmlElement('w:r')
        properties = OxmlElement('w:rPr')
        color = OxmlElement('w:color')
        color.set(qn('w:val'), '000000')
        properties.append(color)
        run.append(properties)
        text = OxmlElement('w:t')
        text.text = title
        run.append(text)
        link.append(run)
        item._p.append(link)
        item.add_run('\t' + str(number))
    document.add_heading('Материалы к отчёту', level=2)
    paragraph(document, 'Подробная инструкция пользователя и документация по тестированию подготовлены отдельными файлами. Общий отчёт описывает устройство системы; пошаговые операции и полные сценарии проверки приведены в профильных документах комплекта.')


def cover(document):
    """Create the agreed title page without institution or reviewer fields."""
    for text, size, before, bold, right, title in [
        ('ОБЩАЯ ДОКУМЕНТАЦИЯ', 18, 135, True, False, False),
        ('Молочная ферма Луговая', 24, 10, True, False, True),
        ('Учёт продукции и бронирование в 1С версии 1.2.0', 12, 8, False, False, False),
        ('Дисциплина «Управление проектами»', 12, 0, False, False, False),
        ('Выполнил', 12, 80, False, True, False),
        (AUTHOR, 12, 0, True, True, False),
        ('2026', 12, 160, False, False, False),
    ]:
        item = document.add_paragraph(style='Title' if title else 'Normal')
        item.alignment = WD_ALIGN_PARAGRAPH.LEFT if right else WD_ALIGN_PARAGRAPH.CENTER
        item.paragraph_format.space_before = Pt(before)
        item.paragraph_format.space_after = Pt(10)
        if right:
            item.paragraph_format.left_indent = Cm(8)
        run = item.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(size)
        run.bold = bold


