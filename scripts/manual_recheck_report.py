"""Integrate the independently reported manual recheck without erasing history."""

import json
from pathlib import Path

from document_common import paragraph, table

ROOT = Path(__file__).resolve().parents[1]
TITLES = [
    'Приложение Е Ручная перепроверка',
    'Приложение Е1 Продажа и бронь',
    'Приложение Е2 Продажа по брони',
]


def replace_text(item, text):
    """Replace text while retaining paragraph formatting."""
    item.text = text


def apply(document, start_page, add_screenshot):
    """Apply the manual results supplied by the latest main commit."""
    source = ROOT / 'Документация/04_Тестирование/Протоколы/Ручные/RECHECK-20261029-EFIMOV/results.json'
    record = json.loads(source.read_text())
    if any(item.text == TITLES[0] for item in document.paragraphs):
        return
    cases = {
        'MP03': 'Ожидаемые результаты совпали. Пересчёт сумм работает. Перепроведение не дублирует движения. После отмены Прихода №000000002 склад молока возвращается к 75 л, резерв равен нулю.',
        'MS01': 'Ожидаемые результаты совпали. При изменении количества движения заменяются. Отмена Расхода №000000002 восстанавливает склад и исключает тестовую сумму из продаж. Итог исходных продаж снова 4 890 руб.',
        'MS02': 'Ожидаемые результаты совпали. Бронь создаёт резерв 20 л, перепроводится без дублирования и отменяется. Состояния на снимках: 75 / 20 / 55 и 75 / 0 / 75 л.',
        'MS03': 'По записи исполнителя продажа по брони списывает резерв, а отмена Расхода возвращает товар в резерв. Снимки показывают результат продажи 55 / 0 / 55 л и итоговое восстановление 75 / 0 / 75 л после завершения сценария.',
    }
    current = None
    for item in document.paragraphs:
        text = item.text
        if item.style.name == 'Heading 2':
            current = text[:4] if text[:4] in cases else None
        elif item.style.name == 'Heading 1':
            current = None
        if current and text.startswith('Роль:'):
            role = 'Покупка' if current == 'MP03' else 'Продажа'
            replace_text(item, f'Роль: {role}. Статус: Успешно по ручной перепроверке 29.10.2026. Приоритет: P1.')
        elif current and text.startswith('Фактический результат:'):
            replace_text(item, 'Фактический результат: ' + cases[current])
        elif current and text.startswith('Статус и исполнитель:'):
            replace_text(item, 'Статус и исполнитель: Успешно, Ефимов С.Р.; ручная перепроверка 29.10.2026. Источник: дополнение dab3be8, приложение Е.')
        elif current and text.startswith('Отклонение и номер дефекта:'):
            defect = 'DEF-001' if current == 'MP03' else 'DEF-002'
            replace_text(item, f'Отклонение: устранено. {defect} закрыт по сообщению Ефимова С.Р. от 29.10.2026. История первоначального отказа сохранена в разделе 8; автоматическая перепроверка — приложение Г.')
        elif text.startswith('Объект испытаний — конфигурация'):
            replace_text(item, 'Объект испытаний — конфигурация «Молочная ферма Луговая». Отчёт сохраняет историю версии 1.2.0, результаты исправлений DEF-001 и DEF-002 в 1.2.1 и ручное дополнение Ефимова С.Р. от 29 октября 2026 года. Автоматическая перепроверка приведена в приложении Г, новые ручные результаты и снимки — в приложении Е. Платформа: 1С 8.3.27.1688, учебная версия.')
        elif text.startswith('Отчёт разделяет ручные и автоматические испытания.'):
            replace_text(item, 'В прогоне 28 октября успешны 8 сценариев, 4 остановлены DEF-001/DEF-002. Ефимов С.Р. сообщил об успешной перепроверке этих четырёх сценариев 29 октября и приложил снимки. В 1.2.1 успешны 55 проверок форм и прав и 83 проверки регрессии. Полный smoke-тест отмечен исполнителем пройденным; повторный журнал не приложен.')
        elif text.startswith('Ручной smoke-тест 28.10.2026 не пройден:'):
            replace_text(item, 'Исходный журнал 28.10.2026 содержит блокировки SM05–SM11. В дополнении от 29 октября Ефимов С.Р. отметил SM01–SM12 пройденными, но оставил таблицу повторного журнала пустой. Сохранены оба состояния: исторический журнал — раздел 8, сведения о перепроверке и новые снимки — приложение Е. Автоматические проверки учтены отдельно.')
        elif text.startswith('DEF-001 и DEF-002 исправлены в версии 1.2.1.'):
            replace_text(item, 'DEF-001 и DEF-002 исправлены в 1.2.1. Автоматическая проверка: 55 проверок форм и прав, 83 проверки регрессии — успешны. Ефимов С.Р. дополнительно сообщил об успешной ручной перепроверке MP03 и MS01–MS03 и закрыл дефекты 29 октября; новые снимки включены в приложение Е. Полный smoke-тест отмечен исполнителем пройденным, однако его повторный пошаговый журнал отсутствует.')
        elif text.startswith('DEF-001 и DEF-002 исправлены и прошли автоматическую перепроверку.'):
            replace_text(item, 'Автоматическая перепроверка DEF-001 и DEF-002 успешна. Позднее Ефимов С.Р. сообщил о ручном подтверждении исправлений и закрыл дефекты; см. приложение Е. Эти результаты сохранены отдельно от старого журнала и автоматизации. Для полного документального подтверждения smoke-теста требуется заполнить повторный пошаговый журнал.')
            for run in item.runs:
                run.bold = True
    for grid in document.tables:
        is_defect = any('MP03 шаги 4 и 5' in c.text or 'MS01 шаг 2, MS02 шаг 3' in c.text for row in grid.rows for c in row.cells)
        for row in grid.rows:
            key = row.cells[0].text
            if key == 'Ручные сценарии' and len(row.cells) == 3:
                row.cells[-1].text = '12 успешны; 4 перепроверены 29.10'
            elif key == 'Smoke-тест' and len(row.cells) == 3:
                row.cells[-1].text = 'Пройден по отчёту; журнал не приложен'
            if is_defect:
                if key == 'Важность и состояние':
                    row.cells[-1].text = 'Высокая. Исправлен в 1.2.1. Закрыт по сообщению Ефимова С.Р. от 29.10.2026.'
                elif key == 'Перепроверка':
                    row.cells[-1].text += ' Ручной повтор: Ефимов С.Р., 29.10.2026, успешно; приложение Е.'
                elif key == 'Доказательства':
                    row.cells[-1].text = row.cells[-1].text.replace('Скриншот MP03-bug-rights.png;', 'Исторический снимок: Исправление_DEF-001_DEF-002/До_исправления/MP03-bug-rights.png;')
    start_page(document, TITLES[0])
    paragraph(document, 'Ефимов С.Р. передал ручное дополнение 29 октября 2026 года в коммите dab3be8. Фактические результаты MP03, MS01, MS02 и MS03 изменены на успешные; DEF-001 и DEF-002 отмечены закрытыми. Старые отказы сохранены в карточках раздела 8 и исходных протоколах.')
    table(document, ['Сценарий', 'Сообщение исполнителя', 'Доказательство'], [
        ('MP03', 'Приход перепроводится без дублей и отменяется', 'MP03-stock.png'),
        ('MS01', 'Движения изменяются, отмена восстанавливает итог', 'MS01-sale.png'),
        ('MS02', 'Резерв создаётся и освобождается', 'MS02-booked.png; MS02-cancelled.png'),
        ('MS03', 'Связанная продажа и обратный переход работают', 'MS03-linked-sale.png; MS03-restored.png'),
    ], [0.65, 3.6, 2.3])
    paragraph(document, 'На снимках указана дата отчётов 29.10.2026. Точная версия повторной ручной базы в дополнении не названа. Полный smoke-тест отмечен исполнителем пройденным, но таблица его повторного журнала пустая. Эти сведения не заменяются результатами автоматизации 1.2.1.')
    add_screenshot(document, 'MP03-stock.png', 935, 'Рисунок Е.1 После отмены тестового прихода: молоко 75 / 0 / 75 л')
    start_page(document, TITLES[1])
    paragraph(document, 'Снимки MS02 относятся к двум состояниям одной ветви проверки. Порядок значений: на складе / в резерве / свободно. Оригинальные PNG сохранены в папке RUN-20261028-01; дата отчётов — 29 октября.')
    add_screenshot(document, 'MS01-sale.png', 1037, 'Рисунок Е.2 После отмены тестовой продажи исходный итог равен 4 890 руб.')
    add_screenshot(document, 'MS02-booked.png', 758, 'Рисунок Е.3 Бронь 20 л: молоко 75 / 20 / 55 л')
    add_screenshot(document, 'MS02-cancelled.png', 905, 'Рисунок Е.4 После отмены брони: молоко 75 / 0 / 75 л')
    start_page(document, TITLES[2])
    paragraph(document, 'Снимок MS03-linked-sale показывает результат продажи по брони. MS03-restored фиксирует итоговое восстановление склада и освобождение резерва после завершения сценария. Промежуточный возврат в резерв при отмене Расхода указан исполнителем и отдельно подтверждён автоматической проверкой в приложении Г.')
    add_screenshot(document, 'MS03-linked-sale.png', 911, 'Рисунок Е.5 После продажи по брони: молоко 55 / 0 / 55 л')
    add_screenshot(document, 'MS03-restored.png', 925, 'Рисунок Е.6 После завершения сценария: молоко 75 / 0 / 75 л')
    paragraph(document, 'Источник записей: Протоколы/Ручные/RECHECK-20261029-EFIMOV/results.json. Данные ручной перепроверки внесены по отчёту исполнителя; автоматические протоколы и исторические результаты сохранены раздельно.')
